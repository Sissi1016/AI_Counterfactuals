"""Selections for cells merged into the final appendix, without new estimation."""
from __future__ import annotations

import csv


def build(root, macros, parsed):
    sources = {}
    # Script 47 already writes the displayed estimates and intervals as macros.
    names = [
        ("Mean citations of the marginal applications", "MeanY"),
        ("Mean score of the same applications", "MeanS"),
        ("computed from the rejected side (check)", "MeanSRej"),
        ("Score − citations", "Bias"), ("Mean guess", "MeanGuess"),
        ("Mean absolute error: score", "TrimMAE"), ("guess", "TrimMAEGuess"),
        ("share of the guess's error removed (%)", "TrimGainShare"),
        ("Factor that holds 50% of marginal applications: score", "FFiftyAll"),
        ("guess, 50%", "FFiftyGuess"),
        ("Factor that holds 80% of marginal applications: score", "FEightyAll"),
        ("guess, 80%", "FEightyGuess"),
    ]
    rows = [["Measure", "Estimate", "95% CI"]]
    for label, key in names:
        values = [macros["xMvPois" + key], macros["xMvPois" + key + "CI"]]
        rows.append([label] + [v.replace("$-$", "−") for v in values])
    rows.append(["ratio, granted to rejected", macros["xKGrantRatio"], macros["xKGrantRatioCI"]])
    sources["derived:marginal_metrics"] = {"rows": rows,
        "inputs": ["output/latex/c1mv_poisson_numbers.tex", "output/latex/ext_numbers.tex"],
        "generator": "tools/supplementary_sources.py"}

    path = root / "output/tables/c1x_poisson_within.csv"
    with path.open(newline="", encoding="utf-8") as stream:
        data = list(csv.DictReader(stream))
    rows = [["Grouping", "Granted", "Rejected"]]
    for grouping in ("TcYear", "AuYear"):
        selected = {r["key"]: r for r in data if r["grouping"] == grouping}
        rows.append([grouping, f"{float(selected['gr']['value']):.3f}", f"{float(selected['rej']['value']):.3f}"])
    sources["derived:within_rank_correlations"] = {"rows": rows,
        "inputs": ["output/tables/c1x_poisson_within.csv"], "generator": "tools/supplementary_sources.py"}

    # The displayed names-hidden/shown medians are generated by script 34's table.
    # Join the two cells from that table rather than estimating or rounding anew.
    source_row = next(r for r in parsed["output/latex/ext_tab_twins_names.tex"]["rows"]
                      if r[0].startswith("Leniency twins"))
    sources["derived:twin_name_gap"] = {"rows": [["Measure", "Gap, hidden / shown"],
        ["Gender gap in decisions, names hidden / shown", source_row[1] + " / " + source_row[2]]],
        "inputs": ["output/latex/ext_tab_twins_names.tex"], "generator": "tools/supplementary_sources.py"}
    path = root / "output/tables/c1_kllm_all_poisson_contraction.csv"
    with path.open(newline="", encoding="utf-8") as stream:
        row = next(r for r in csv.DictReader(stream) if r["rule"] == "Random" and r["outcome"] == "cites"
                   and r["sample"] == "test + imputation" and r["quintile"] == "2–5 (mean)")
    sources["derived:random_loss"] = {"rows": [["Rule", "Citations lost (%)"],
        ["Random rejections", f"{-100 * float(row['change_at_examiner_rejections']):.1f}"]],
        "inputs": ["output/tables/c1_kllm_all_poisson_contraction.csv"], "generator": "tools/supplementary_sources.py"}
    return sources
